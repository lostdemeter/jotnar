# LM depth-2 weight-tied (2x H=2 blocks, S<=8, V=513 frozen).
#
# First depth run (compounding decider): layer 1 from toks via GATHER,
# layer 2 from H2 directly (no gather), SAME weights both layers
# (tied -- isolates compounding from cross-regime effects; distinct
# L0/L1 banks are the follow-up). Per-head Dh=8, WIDE throughout.
CONFIG eps_rms 1e-6
CONFIG beta -30.0
IMPORT "mlp.asm"

IN tok
IN pos
IN cmask
IN emb
IN wq
IN wk
IN wv
IN wo
IN wup
IN wgate
IN wdown
IN rms_w1
IN rms_w2
IN wlog
IN ukt
IN evb

E = GATHER(emb, tok)
XN = RMSNORM(E, rms_w1)
Q = MATMUL(XN, wq)
K = MATMUL(XN, wk)
V = MATMUL(XN, wv)
Q1 = SLICE(Q, 1, 0, 8)
Q2 = SLICE(Q, 1, 8, 16)
K1 = SLICE(K, 1, 0, 8)
K2 = SLICE(K, 1, 8, 16)
V1 = SLICE(V, 1, 0, 8)
V2 = SLICE(V, 1, 8, 16)
QR1 = ROTARY(Q1, pos)
QR2 = ROTARY(Q2, pos)
KR1 = ROTARY(K1, pos)
KR2 = ROTARY(K2, pos)
KT1 = TRANSPOSE(KR1)
KT2 = TRANSPOSE(KR2)
SC1 = BATCH_MATMUL(QR1, KT1)
SC2 = BATCH_MATMUL(QR2, KT2)
NEG1 = BETA(SC1)
MS1 = SELECT(cmask, SC1, NEG1)
MS2 = SELECT(cmask, SC2, NEG1)
S1 = TSHIFT(MS1)
S2 = TSHIFT(MS2)
P1 = SOFTMAX_WIDE(S1)
P2 = SOFTMAX_WIDE(S2)
C1 = BATCH_MATMUL(P1, V1)
C2 = BATCH_MATMUL(P2, V2)
CTX = CONCAT(C1, C2, 1)
O = MATMUL(CTX, wo)
H = ADD(E, O)
HN = RMSNORM(H, rms_w2)
BC1 = MATMUL(HN, ukt)
BS1 = TSHIFT(BC1)
BP1 = SOFTMAX_WIDE(BS1)
BDOWN = MATMUL(BP1, evb)
H2 = ADD(H, BDOWN)
XN2 = RMSNORM(H2, rms_w1)
Q2A = MATMUL(XN2, wq)
K2A = MATMUL(XN2, wk)
V2A = MATMUL(XN2, wv)
Q12 = SLICE(Q2A, 1, 0, 8)
Q22 = SLICE(Q2A, 1, 8, 16)
K12 = SLICE(K2A, 1, 0, 8)
K22 = SLICE(K2A, 1, 8, 16)
V12 = SLICE(V2A, 1, 0, 8)
V22 = SLICE(V2A, 1, 8, 16)
QR12 = ROTARY(Q12, pos)
QR22 = ROTARY(Q22, pos)
KR12 = ROTARY(K12, pos)
KR22 = ROTARY(K22, pos)
KT12 = TRANSPOSE(KR12)
KT22 = TRANSPOSE(KR22)
SC12 = BATCH_MATMUL(QR12, KT12)
SC22 = BATCH_MATMUL(QR22, KT22)
NEG2 = BETA(SC12)
MS12 = SELECT(cmask, SC12, NEG2)
MS22 = SELECT(cmask, SC22, NEG2)
S12 = TSHIFT(MS12)
S22 = TSHIFT(MS22)
P12 = SOFTMAX_WIDE(S12)
P22 = SOFTMAX_WIDE(S22)
C12 = BATCH_MATMUL(P12, V12)
C22 = BATCH_MATMUL(P22, V22)
CTX2 = CONCAT(C12, C22, 1)
O2 = MATMUL(CTX2, wo)
H3 = ADD(H2, O2)
HN2 = RMSNORM(H3, rms_w2)
BC2 = MATMUL(HN2, ukt)
BS2 = TSHIFT(BC2)
BP2 = SOFTMAX_WIDE(BS2)
BDOWN2 = MATMUL(BP2, evb)
H4 = ADD(H3, BDOWN2)
XN3 = RMSNORM(H4, rms_w1)
Q3A = MATMUL(XN3, wq)
K3A = MATMUL(XN3, wk)
V3A = MATMUL(XN3, wv)
Q13 = SLICE(Q3A, 1, 0, 8)
Q23 = SLICE(Q3A, 1, 8, 16)
K13 = SLICE(K3A, 1, 0, 8)
K23 = SLICE(K3A, 1, 8, 16)
V13 = SLICE(V3A, 1, 0, 8)
V23 = SLICE(V3A, 1, 8, 16)
QR13 = ROTARY(Q13, pos)
QR23 = ROTARY(Q23, pos)
KR13 = ROTARY(K13, pos)
KR23 = ROTARY(K23, pos)
KT13 = TRANSPOSE(KR13)
KT23 = TRANSPOSE(KR23)
SC13 = BATCH_MATMUL(QR13, KT13)
SC23 = BATCH_MATMUL(QR23, KT23)
NEG3 = BETA(SC13)
MS13 = SELECT(cmask, SC13, NEG3)
MS23 = SELECT(cmask, SC23, NEG3)
S13 = TSHIFT(MS13)
S23 = TSHIFT(MS23)
P13 = SOFTMAX_WIDE(S13)
P23 = SOFTMAX_WIDE(S23)
C13 = BATCH_MATMUL(P13, V13)
C23 = BATCH_MATMUL(P23, V23)
CTX3 = CONCAT(C13, C23, 1)
O3 = MATMUL(CTX3, wo)
H5 = ADD(H4, O3)
HN3 = RMSNORM(H5, rms_w2)
BC3 = MATMUL(HN3, ukt)
BS3 = TSHIFT(BC3)
BP3 = SOFTMAX_WIDE(BS3)
BDOWN3 = MATMUL(BP3, evb)
H6 = ADD(H5, BDOWN3)
XN4 = RMSNORM(H6, rms_w1)
Q4A = MATMUL(XN4, wq)
K4A = MATMUL(XN4, wk)
V4A = MATMUL(XN4, wv)
Q14 = SLICE(Q4A, 1, 0, 8)
Q24 = SLICE(Q4A, 1, 8, 16)
K14 = SLICE(K4A, 1, 0, 8)
K24 = SLICE(K4A, 1, 8, 16)
V14 = SLICE(V4A, 1, 0, 8)
V24 = SLICE(V4A, 1, 8, 16)
QR14 = ROTARY(Q14, pos)
QR24 = ROTARY(Q24, pos)
KR14 = ROTARY(K14, pos)
KR24 = ROTARY(K24, pos)
KT14 = TRANSPOSE(KR14)
KT24 = TRANSPOSE(KR24)
SC14 = BATCH_MATMUL(QR14, KT14)
SC24 = BATCH_MATMUL(QR24, KT24)
NEG4 = BETA(SC14)
MS14 = SELECT(cmask, SC14, NEG4)
MS24 = SELECT(cmask, SC24, NEG4)
S14 = TSHIFT(MS14)
S24 = TSHIFT(MS24)
P14 = SOFTMAX_WIDE(S14)
P24 = SOFTMAX_WIDE(S24)
C14 = BATCH_MATMUL(P14, V14)
C24 = BATCH_MATMUL(P24, V24)
CTX4 = CONCAT(C14, C24, 1)
O4 = MATMUL(CTX4, wo)
H7 = ADD(H6, O4)
HN4 = RMSNORM(H7, rms_w2)
BC4 = MATMUL(HN4, ukt)
BS4 = TSHIFT(BC4)
BP4 = SOFTMAX_WIDE(BS4)
BDOWN4 = MATMUL(BP4, evb)
H8 = ADD(H7, BDOWN4)
LOGITS = MATMUL(H8, wlog)
OUT = ARGMAX(LOGITS, 1)
